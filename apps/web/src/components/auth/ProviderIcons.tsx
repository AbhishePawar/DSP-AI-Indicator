export function ProviderIcon({
  provider,
  className,
}: {
  provider: string;
  className?: string;
}) {
  switch (provider.toUpperCase()) {
    case "GOOGLE":
      return <GoogleIcon className={className} />;
    case "MICROSOFT":
      return <MicrosoftIcon className={className} />;
    case "FACEBOOK":
      return <FacebookIcon className={className} />;
    default:
      return null;
  }
}
